export type PixelIcon = {
  id: string;
  name: string;
  category: string;
  rows: readonly string[];
};

// Original 12-cell drawings, framed by two empty cells on every side.
// Each # is a filled cell; the holes are deliberate, not stroked outlines.
function pixel(id: string, name: string, category: string, drawing: string): PixelIcon {
  const rows = drawing.trim().split('\n').map((row) => `..${row.trim()}..`);
  return { id, name, category, rows: ['................', '................', ...rows, '................', '................'] };
}

