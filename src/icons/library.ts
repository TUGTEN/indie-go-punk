/** Enumerate horizontal runs once for both vector and canvas renderers. */
function runs(icon: PixelIcon, visit: (x: number, y: number, width: number) => void): void {
  icon.rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      if (row[x] !== '#') { x++; continue; }
      const start = x;
      while (row[x] === '#') x++;
      visit(start, y, x - start);
    }
  });
}

export function iconPath(icon: PixelIcon): string {
  const paths: string[] = [];
  runs(icon, (x, y, width) => paths.push(`M${x} ${y}h${width}v1h-${width}z`));
  return paths.join('');
}

function escapeXml(text: string): string {
  return text.replace(/[<>&"']/g, (char) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&apos;' })[char]!);
}

export function iconSvg(icon: PixelIcon, color = '#111111', scale = 8): string {
  if (!/^#[0-9a-fA-F]{6}$/.test(color)) throw new Error('Color must be a six-digit hex color');
  const size = 16 * (Number.isFinite(scale) ? Math.min(64, Math.max(1, Math.round(scale))) : 8);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges"><title>${escapeXml(icon.name)}</title><path fill="${color}" d="${iconPath(icon)}"/></svg>`;
}

export function drawPixelIcon(ctx: CanvasRenderingContext2D, icon: PixelIcon, x: number, y: number, pixelSize: number, color: string): void {
  ctx.fillStyle = color;
  runs(icon, (column, row, width) => ctx.fillRect(x + column * pixelSize, y + row * pixelSize, width * pixelSize, pixelSize));
}
